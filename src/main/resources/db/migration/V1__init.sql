SELECT
    ROUND((20 + random() * 5000)::numeric, 2),
    NOW() - (random() * interval '180 days'),
    NULL,
    p.producto_id,
    'COMPRA'
FROM productos p
WHERE NOT EXISTS (
    SELECT 1 FROM precios pr
    WHERE pr.producto_id = p.producto_id AND pr.tipo = 'COMPRA'
);

INSERT INTO precios (monto, desde, hasta, producto_id, tipo)
SELECT
    ROUND((compra.monto * (1.3 + random()))::numeric, 2),
    compra.desde + interval '1 hour',
    NULL,
    compra.producto_id,
    'VENTA'
FROM (
    SELECT pr.producto_id, pr.monto, pr.desde
    FROM precios pr
    WHERE pr.tipo = 'COMPRA'
      AND NOT EXISTS (
          SELECT 1 FROM precios pv
          WHERE pv.producto_id = pr.producto_id AND pv.tipo = 'VENTA'
      )
) compra;

