create table categorias (
    activo boolean not null,
    categoria_id bigint generated by default as identity,
    fecha_creacion timestamp(6) not null,
    negocio_id bigint not null,
    descripcion varchar(100) not null,
    primary key (categoria_id),
    unique (descripcion, negocio_id)
);

create table clientes (
    activo boolean not null,
    cliente_id bigint generated by default as identity,
    fecha_creacion timestamp(6) not null,
    negocio_id bigint not null,
    telefono varchar(20),
    nombre_completo varchar(100) not null,
    primary key (cliente_id)
);

create table compras (
    recibida boolean not null,
    compra_id bigint generated by default as identity,
    fecha_carga timestamp(6) not null,
    fecha_recepcion timestamp(6),
    negocio_id bigint not null,
    usuario_id bigint not null,
    primary key (compra_id)
);

create table formas_pago (
    forma_id bigint generated by default as identity,
    descripcion varchar(100) not null unique,
    primary key (forma_id)
);

create table items_compras (
    cantidad integer not null,
    compra_id bigint not null,
    item_compra_id bigint generated by default as identity,
    precio_id bigint not null,
    producto_id bigint not null,
    primary key (item_compra_id)
);

create table items_ventas (
    cantidad integer not null,
    item_venta_id bigint generated by default as identity,
    precio_id bigint not null,
    producto_id bigint not null,
    venta_id bigint not null,
    primary key (item_venta_id)
);

create table negocios (
    activo boolean not null,
    fecha_creacion timestamp(6),
    negocio_id bigint generated by default as identity,
    parametro_id bigint unique,
    nombre_negocio varchar(100) not null unique,
    primary key (negocio_id)
);

create table parametros (
    parametro_id bigint generated by default as identity,
    una_compra_distintos_proveedores boolean not null,
    exigir_forma_de_pago_al_cargar_venta boolean not null,
    exigir_cliente_al_cargar_venta boolean not null,
    permitir_vender_sin_stock boolean not null,
    empleado_puede_cargar_compras boolean not null,
    empleado_puede_utilizar_abm boolean not null,
    primary key (parametro_id)
);

create table precios (
    monto numeric(38,2) not null,
    desde timestamp(6) not null,
    hasta timestamp(6),
    precio_id bigint generated by default as identity,
    producto_id bigint not null,
    tipo varchar(255) not null check ((tipo in ('COMPRA','VENTA'))),
    primary key (precio_id)
);

create table subcategorias (
    activo boolean not null,
    subcategoria_id bigint generated by default as identity,
    fecha_creacion timestamp(6) not null,
    categoria_id bigint not null,
    descripcion varchar(100) not null,
    primary key (subcategoria_id),
    unique (descripcion, categoria_id)
);

create table productos (
    activo boolean not null,
    stock integer not null,
    categoria_id bigint,
    fecha_creacion timestamp(6) not null,
    negocio_id bigint not null,
    producto_id bigint generated by default as identity,
    proveedor_id bigint,
    subcategoria_id bigint,
    descripcion varchar(100) not null,
    primary key (producto_id),
    unique (descripcion, negocio_id)
);

create table proveedores (
    activo boolean not null,
    negocio_id bigint not null,
    proveedor_id bigint generated by default as identity,
    telefono varchar(20),
    descripcion varchar(100) not null,
    primary key (proveedor_id)
);

create table usuarios (
    activo boolean not null,
    fecha_creacion timestamp(6) not null,
    negocio_id bigint not null,
    ultimo_acceso timestamp(6),
    usuario_id bigint generated by default as identity,
    nombre_completo varchar(100),
    email varchar(255) not null,
    password varchar(255) not null,
    rol varchar(255) not null check ((rol in ('SUPERADMIN','ADMIN','GERENTE','EMPLEADO'))),
    primary key (usuario_id)
);

create table ventas (
    cliente_id bigint not null,
    fecha_hora timestamp(6) not null,
    forma_id bigint,
    negocio_id bigint not null,
    usuario_id bigint not null,
    venta_id bigint generated by default as identity,
    primary key (venta_id)
);

